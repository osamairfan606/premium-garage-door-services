// Converts source images in /assets-src into responsive WebP files in /public/images
// and writes src/config/images.generated.ts with intrinsic dimensions (prevents layout shift).
// Run with: npm run images
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'assets-src');
const OUT = path.join(ROOT, 'public', 'images');
fs.mkdirSync(OUT, { recursive: true });

const PHOTO_WIDTHS = [480, 800, 1280, 1800];

/** @type {{name:string, file:string, widths?:number[], source:'company'|'stock'|'brand', trim?:boolean, png?:boolean}[]} */
const jobs = [];
for (const f of fs.readdirSync(path.join(SRC, 'company'))) {
  const name = f.replace(/\.\w+$/, '');
  if (name === 'logo') continue;
  jobs.push({ name, file: `company/${f}`, source: 'company', widths: name.startsWith('offer') ? [480, 800, 1080] : PHOTO_WIDTHS });
}
for (const f of fs.readdirSync(path.join(SRC, 'stock'))) {
  jobs.push({ name: f.replace(/\.\w+$/, ''), file: `stock/${f}`, source: 'stock', widths: PHOTO_WIDTHS });
}
for (const f of fs.readdirSync(path.join(SRC, 'brands'))) {
  jobs.push({ name: `brand-${f.replace(/\.\w+$/, '')}`, file: `brands/${f}`, source: 'brand', widths: [320], trim: true });
}

const manifest = {};
for (const job of jobs) {
  let base = sharp(path.join(SRC, job.file));
  if (job.trim) base = base.trim();
  const buf = await base.toBuffer();
  const meta = await sharp(buf).metadata();
  const widths = [...new Set((job.widths ?? PHOTO_WIDTHS).map(w => Math.min(w, meta.width)))];
  for (const w of widths) {
    await sharp(buf).resize({ width: w, withoutEnlargement: true }).webp({ quality: job.source === 'brand' ? 90 : 72, effort: 5 }).toFile(path.join(OUT, `${job.name}-${w}.webp`));
  }
  manifest[job.name] = { width: meta.width, height: meta.height, widths, source: job.source };
  console.log('✓', job.name, widths.join(','));
}

// Logo: trimmed full lockup + square mark for favicon / loader.
const logo = await sharp(path.join(SRC, 'company/logo.png')).trim().toBuffer();
const lm = await sharp(logo).metadata();
await sharp(logo).resize({ width: 480 }).webp({ quality: 92 }).toFile(path.join(OUT, 'logo-480.webp'));
await sharp(logo).resize({ width: 480 }).png({ compressionLevel: 9 }).toFile(path.join(OUT, 'logo-480.png'));
// The house mark occupies roughly the top 60% of the trimmed lockup.
const markH = Math.round(lm.height * 0.6);
const mark = await sharp(logo).extract({ left: 0, top: 0, width: lm.width, height: markH }).trim().toBuffer();
const mm = await sharp(mark).metadata();
const side = Math.max(mm.width, mm.height) + 40;
const square = await sharp({ create: { width: side, height: side, channels: 4, background: { r: 14, g: 15, b: 17, alpha: 1 } } })
  .composite([{ input: mark, gravity: 'center' }]).png().toBuffer();
await sharp(square).resize(512).png().toFile(path.join(ROOT, 'public', 'icon-512.png'));
await sharp(square).resize(180).png().toFile(path.join(ROOT, 'public', 'apple-touch-icon.png'));
await sharp(square).resize(48).png().toFile(path.join(ROOT, 'public', 'favicon.png'));
await sharp(mark).resize({ width: 160 }).webp({ quality: 92 }).toFile(path.join(OUT, 'logo-mark-160.webp'));
manifest['logo'] = { width: lm.width, height: lm.height, widths: [480], source: 'company' };
// Social share image (1200x630) built from the company hero photo.
await sharp(path.join(SRC, 'company/hero-home.png')).resize(1200, 630, { fit: 'cover' }).jpeg({ quality: 80 }).toFile(path.join(ROOT, 'public', 'og-image.jpg'));

const ts = `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.\nexport const imageManifest = ${JSON.stringify(manifest, null, 2)} as const;\nexport type ImageName = keyof typeof imageManifest;\n`;
fs.writeFileSync(path.join(ROOT, 'src', 'config', 'images.generated.ts'), ts);
console.log('manifest written');
